-- 공지 배너의 기본 문구를 비운다.
--
-- 무슨 일이 있었나: `system_settings.notice_text` 에는 초기 마이그레이션(20260602120000)이
-- 시드로 넣은 문장이 들어 있었다.
--
--   "경주 황리단길 실시간 혼잡도와 대안 장소 추천을 제공합니다.
--    축제·행사 기간에는 혼잡도가 평소보다 높을 수 있습니다."
--
-- 이 값은 **여태 아무도 읽지 않아서** 화면에 나타난 적이 없다(검토목록 6번 — 설정 4개가 어디에도
-- 연결돼 있지 않았다). 2026-09-07 에 `GET /api/v1/system/public-settings` 로 관광객 앱에
-- 배선하자 그 순간부터 모든 방문자의 화면 상단에 고정 배너로 뜨기 시작했다.
--
-- 왜 비우나: 저 문장은 **공지가 아니라 서비스 소개**다. 공지 자리에 상시 안내를 넣어 두면
-- 진짜 공지(축제 통제·점검 예정 같은 것)가 올라왔을 때 사용자가 그것도 늘 있던 배너로 읽고
-- 넘긴다. 공지 채널은 비워 두어야 공지로 작동한다.
--
-- 조건부로 비우는 이유: 그 사이 담당자가 **실제 공지를 써 넣었을 수 있다.** 시드 문구와 정확히
-- 같을 때만 비운다 — 사람이 고른 문장을 마이그레이션이 말없이 지우면 안 된다.
--
-- 새 환경도 함께 정리된다: RESET_AND_SETUP.sql 은 마이그레이션을 순서대로 이어 붙이므로,
-- 위 시드 INSERT 뒤에 이 UPDATE 가 실행되어 신규 셋업도 빈 공지로 시작한다.
-- (칼럼 DEFAULT 는 원래 '' 이므로 손댈 것이 없다.)
--
-- 공지를 다시 쓰려면 관리자 설정 화면에서 입력하면 된다(저장 경로는 살아 있다).

UPDATE public.system_settings
SET notice_text = ''
WHERE notice_text = '경주 황리단길 실시간 혼잡도와 대안 장소 추천을 제공합니다. 축제·행사 기간에는 혼잡도가 평소보다 높을 수 있습니다.';
